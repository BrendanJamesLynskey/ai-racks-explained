/**
 * /specs: every hardware figure the model uses, with its status, source
 * and access date, and the quoted claims the site shows but never uses as
 * inputs. Server Component, static.
 */
import {
  FIELD_INFO,
  FieldCell,
  SpecTable,
  SwitchTable,
} from "@/components/mdx/Tables";
import {
  ACCESSED,
  CLAIMS,
  COST_ILLUSTRATIVE,
  FACILITY_RECORDS,
  GPU_RECORDS,
  LLAMA3_RUN,
  OTHER_RECORDS,
  PHYS,
  SOURCES,
  SUPERPOD_RULES,
  SYSTEM_RECORDS,
  type Field,
} from "@/lib/racks/model";
import { repoFile } from "@/lib/site";

export const metadata = {
  title: "Specifications",
  description:
    "Every hardware figure AI Racks Explained uses, with its status (stated, derived, not disclosed), its source and the date it was read.",
};

const A =
  "focus-ring rounded text-accent underline underline-offset-2 dark:text-indigo-300";

const LABELS: Record<string, string> = {
  gpus: "GPUs in the run",
  tp: "Tensor parallel",
  pp: "Pipeline stages",
  dp: "Data-parallel replicas",
  days: "Days in the reliability record",
  unexpected: "Unexpected interruptions",
  server_gpus: "GPUs per NVLink server",
  capex_rack_usd: "Capital cost per rack (USD)",
  years: "Write-off period (years)",
  pue: "PUE (facility over IT power)",
  usd_per_kwh: "Electricity (USD per kWh)",
  utilisation: "Utilisation",
};

function FieldRows({
  fields,
  label,
}: {
  fields: Record<string, Field>;
  label: string;
}): JSX.Element {
  return (
    <div
      className="my-6 overflow-x-auto"
      tabIndex={0}
      role="region"
      aria-label={label}
    >
      <table className="w-full text-sm">
        <tbody>
          {Object.entries(fields).map(([k, f]) => (
            <tr key={k}>
              <th scope="row" className="text-left font-normal">
                {FIELD_INFO[k]?.label ?? LABELS[k] ?? k}
              </th>
              <td>
                <FieldCell f={f} k={k} />
              </td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

export default function SpecsPage(): JSX.Element {
  const gpuFields = Object.keys(GPU_RECORDS[0]!.fields).filter(
    (k) => k !== "hbm_gen",
  );
  return (
    <main className="mx-auto max-w-5xl px-4 py-12 sm:px-6">
      <p className="font-mono text-xs uppercase tracking-widest text-accent dark:text-indigo-300">
        /specs
      </p>
      <h1 className="mt-2 text-3xl font-semibold tracking-tight">
        Specifications and sources
      </h1>
      <div className="mdx-content mt-6">
        <p>
          Every figure below was read from its source on <b>{ACCESSED}</b>. A
          figure is either stated by the vendor, <i>derived</i> from stated
          figures (the formula is in the model), or <i>not disclosed</i> in the
          sources used: gaps are never filled with a guess. Hover a source tag
          for the source&apos;s title, its access date and where in it the
          figure is. Availability: <i>product</i> (a vendor product page lists
          the specifications), <i>preliminary</i> (the vendor marks them
          preliminary or projected), <i>planned</i> (the vendor gives a future
          date). The same table, generated by the model&apos;s script, is{" "}
          <a href={repoFile("results.md")} className={A}>
            results.md
          </a>
          .
        </p>
        <h2 id="gpus">GPUs</h2>
        <SpecTable
          kind="gpu"
          ids={GPU_RECORDS.map((g) => g.id).join(",")}
          fields={gpuFields.join(",")}
        />
        {SYSTEM_RECORDS.map((s) => (
          <section key={s.id} aria-labelledby={`sys-${s.id}`}>
            <h2 id={`sys-${s.id}`}>
              {s.name}
              {s.avail.v !== "product" ? ` (${s.avail.v})` : ""}
            </h2>
            <SpecTable
              kind="system"
              ids={s.id}
              fields={Object.keys(s.fields).join(",")}
            />
          </section>
        ))}
        <h2 id="switches">Scale-out switches</h2>
        <SwitchTable />
        <h2 id="superpod">DGX SuperPOD (GB200) design rules</h2>
        <div
          className="my-6 overflow-x-auto"
          tabIndex={0}
          role="region"
          aria-label="SuperPOD rules"
        >
          <table className="w-full text-sm">
            <tbody>
              {Object.entries(SUPERPOD_RULES).map(([k, f]) => (
                <tr key={k}>
                  <th scope="row" className="text-left font-normal">
                    {FIELD_INFO[k]?.label ?? k}
                  </th>
                  <td>
                    <FieldCell f={f} k={k} />
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
        {FACILITY_RECORDS.map((r) => (
          <section key={r.id} aria-labelledby={`fac-${r.id}`}>
            <h2 id={`fac-${r.id}`}>{r.name}</h2>
            <SpecTable
              kind="facility"
              ids={r.id}
              fields={Object.keys(r.fields).join(",")}
            />
          </section>
        ))}
        <h2 id="physics">Physical properties</h2>
        <p>
          Water&apos;s specific heat is computed from NIST&apos;s Shomate
          equation at {PHYS.shomate.T} K (chapter 7); air&apos;s from
          NASA&apos;s ratio of specific heats and gas constant.
        </p>
        <FieldRows fields={PHYS.fields} label="Physical properties" />
        <h2 id="others">Other rack- and pod-scale designs</h2>
        {OTHER_RECORDS.map((r) => (
          <section key={r.id} aria-labelledby={`other-${r.id}`}>
            <h3 id={`other-${r.id}`}>
              {r.name}
              {r.avail.v !== "product" ? ` (${r.avail.v})` : ""}
            </h3>
            <SpecTable
              kind="other"
              ids={r.id}
              fields={Object.keys(r.fields).join(",")}
            />
          </section>
        ))}
        <h2 id="llama3">Llama 3 405B pre-training (chapter 9)</h2>
        <FieldRows fields={LLAMA3_RUN} label="Llama 3 run" />
        <h2 id="cost">Illustrative cost inputs (chapter 11)</h2>
        <p>Round numbers chosen for the picture, not prices or quotes:</p>
        <FieldRows fields={COST_ILLUSTRATIVE} label="Cost inputs" />
        <h2 id="claims">Quoted claims</h2>
        <p>Shown where relevant, attributed, and never used as model inputs:</p>
        <ul>
          {Object.entries(CLAIMS).map(([id, c]) => (
            <li key={id}>
              {c.text} (
              <a href={SOURCES[c.src]!.url} className={A}>
                {SOURCES[c.src]!.title}
              </a>
              )
            </li>
          ))}
        </ul>
        <h2 id="sources">Sources</h2>
        <ul>
          {Object.entries(SOURCES).map(([id, s]) => (
            <li key={id} data-source={id}>
              <code>{id}</code>:{" "}
              <a href={s.url} className={A}>
                {s.title}
              </a>{" "}
              ({s.kind}, read {s.accessed})
            </li>
          ))}
        </ul>
      </div>
    </main>
  );
}
